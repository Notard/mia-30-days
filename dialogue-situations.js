export function resultLineFor(id,grade){return resultLines[id]?.[grade]||null;}

export function daySituation(s,night=false){
  const today=s.history.filter(h=>h.day===(night?s.day:s.day-1));
  const actions=today.filter(h=>h.activityId);
  const graded=actions.filter(h=>h.activityId!=='rest'&&h.result?.grade);
  const last=graded.at(-1)?.result?.grade;
  if(night){
    if(actions.length===2&&actions.every(h=>h.activityId==='rest'))return 'rested';
    if(last==='disaster'||last==='failure'||last==='great_success')return last;
    if(new Set(actions.map(h=>h.activityId)).size>=2)return 'varied';
    if(s.trust>=65)return 'close';
    return null;
  }
  if(s.day===1)return null;
  if(s.energy<25)return 'tired';
  if(s.money<10)return 'broke';
  if(actions.length===2&&actions.every(h=>h.activityId==='rest'))return 'rested';
  return ['disaster','failure','great_success'].includes(last)?last:null;
}
